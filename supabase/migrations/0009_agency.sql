-- 배분 부서와 회신 기관을 가른다 (2026-08-24)
--
-- ★ 왜 나누는가. `department` 에 시청 과·팀과 외부 기관(시공사·공기업)이 함께 들어가면
--   부서별 집계가 사과와 오렌지를 함께 센다. 이 앱의 최종 목적이 "이런 민원은 어느 과로
--   가는가" 라서, 시청 밖으로 넘어간 건은 **같은 칸에 두면 안 된다.**
--   그리고 "우리가 처리한 것 / 남에게 넘긴 것" 의 비율 자체가 봐야 할 숫자다.
--
--   department = 시청 안에서 맡은 곳   (예: 과천시청 당직실, 공원녹지과 하천관리팀)
--   agency     = 시청 밖에서 답을 준 곳 (예: 넷마블 공사 관계자)
alter table complaints add column if not exists agency text;
